import { api } from "@store/shared";

const d = (p) => p.then((r) => r.data);

export const adminApi = {
  me: () => d(api.get("/admin/me")),
  dashboard: () => d(api.get("/admin/dashboard")),
  products: (params) => d(api.get("/admin/products", { params })),
  product: (id) => d(api.get(`/admin/products/${id}`)),
  publishCheck: (id) => d(api.get(`/admin/products/${id}/publish-check`)),
  createProduct: (body) => d(api.post("/admin/products", body)),
  updateProduct: (id, body) => d(api.patch(`/admin/products/${id}`, body)),
  publish: (id, body) => d(api.post(`/admin/products/${id}/publish`, body || {})),
  unpublish: (id) => d(api.post(`/admin/products/${id}/unpublish`)),
  archive: (id) => d(api.post(`/admin/products/${id}/archive`)),
  duplicate: (id) => d(api.post(`/admin/products/${id}/duplicate`)),
  deleteProduct: (id) => d(api.delete(`/admin/products/${id}`)),
  setOptions: (id, options, skuPrefix) => d(api.post(`/admin/products/${id}/variants`, { options, skuPrefix })),
  updateVariant: (id, body) => d(api.patch(`/admin/variants/${id}`, body)),
  attachImage: (id, body) => d(api.post(`/admin/products/${id}/images`, body)),
  updateImages: (id, images) => d(api.put(`/admin/products/${id}/images`, { images })),
  presign: (file) => d(api.post("/admin/uploads/presign", { filename: file.name, contentType: file.type, size: file.size })),
  upload: (uploadUrl, file, onProgress) =>
    d(api.put(uploadUrl.replace(/^\/api/, ""), file, { headers: { "Content-Type": file.type }, onUploadProgress: (e) => onProgress?.(e.total ? e.loaded / e.total : 0) })),
  bulk: (body) => d(api.post("/admin/products/bulk", body)),
  importCsv: (text, dryRun) => d(api.post(`/admin/products/import?dryRun=${dryRun}`, text, { headers: { "Content-Type": "text/csv" } })),
  exportCsv: () => d(api.get("/admin/products/export", { responseType: "text" })),
  template: () => d(api.get("/admin/products/import/template", { responseType: "text" })),
  adjustStock: (variantId, body) => d(api.post(`/admin/inventory/${variantId}/adjust`, body)),
  inventoryLogs: (params) => d(api.get("/admin/inventory/logs", { params })),
  lowStock: () => d(api.get("/admin/inventory/low-stock")),
  orders: (params) => d(api.get("/admin/orders", { params })),
  order: (id) => d(api.get(`/admin/orders/${id}`)),
  orderStatus: (id, body) => d(api.post(`/admin/orders/${id}/status`, body)),
  coupons: () => d(api.get("/admin/coupons")),
  createCoupon: (b) => d(api.post("/admin/coupons", b)),
  updateCoupon: (id, b) => d(api.patch(`/admin/coupons/${id}`, b)),
  categories: () => d(api.get("/admin/categories")),
  createCategory: (b) => d(api.post("/admin/categories", b)),
  updateCategory: (id, b) => d(api.patch(`/admin/categories/${id}`, b)),
  deleteCategory: (id) => d(api.delete(`/admin/categories/${id}`)),
  users: (params) => d(api.get("/admin/users", { params })),
  setRoles: (id, roles) => d(api.post(`/admin/users/${id}/roles`, { roles })),
  activity: (params) => d(api.get("/admin/activity", { params })),
  markRead: (ids) => d(api.post("/admin/notifications/read", { ids })),
  reconcile: () => d(api.post("/admin/jobs/reconcile")),
};
